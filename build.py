def risks(d):
    out = []
    for (gn, gt, gd), rs in zip(d['groups'], d['risks']):
        cards = []
        for r in rs:
            why = '\n'.join(f'              <p>{p}</p>' for p in r['why'])
            cases = '\n'.join(
                f'                <li><span class="casetag">{E(t)}</span>{c}</li>' for t, c in r['cases'])
            fixes = '\n'.join(
                f'                <li><strong>{E(b)}</strong>{c}</li>' for b, c in r['fix'])
            cards.append(f'''        <article class="risk" id="risk-{r["no"]}">
          <div class="risk__head">
            <span class="risk__num">リスク {r["no"]:02d} ／ {E(r["seg"])}</span>
            <h3>{E(r["h"])}</h3>
            <p class="risk__where">{E(r["where"])}</p>
          </div>
          <div class="risk__grid">
            <div class="rblock rblock--why">
              <h4>なぜ、いま顕在化したのか</h4>
{why}
            </div>
            <div class="rblock rblock--case">
              <h4>実際に起きたこと</h4>
              <ul>
{cases}
              </ul>
            </div>
            <div class="rblock rblock--fix">
              <h4>講じるべき対策</h4>
              <ul>
{fixes}
              </ul>
            </div>
          </div>
        </article>''')
        extra = d.get('protos_after') if gn.startswith('観点 ③') else None
        protos = ''
        if extra:
            tiles = '\n'.join(
                f'        <div class="proto"><b>{E(b)}</b><span>{E(s)}</span></div>' for b, s in extra)
            protos = f'''

      <div class="protos">
{tiles}
      </div>'''
        out.append(f'''    <div class="vgroup">
      <div class="vgroup__hd">
        <span class="vgroup__n">{E(gn)}</span>
        <span class="vgroup__t">{E(gt)}</span>
        <span class="vgroup__d">{E(gd)}</span>
      </div>

      <div class="risks">
{chr(10).join(cards)}
      </div>{protos}
    </div>''')
    return f'''<section class="section">
  <div class="wrap">
    <div class="section__head">
      <span class="section__num">第 3 章 ／ リスク詳細</span>
      <h2>6つのリスクと、いま講じるべき対策</h2>
      <p class="section__sub">3つの観点それぞれについて、「なぜフロンティアAIによって顕在化したのか」「実際に何が起きたのか」「何を講じるべきか」で整理する。事例は原則として直近1年以内、長くとも3年以内のものに限定した。</p>
    </div>

{chr(10).join(out)}

  </div>
</section>'''


